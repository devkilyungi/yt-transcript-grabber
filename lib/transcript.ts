// Turning caption snippets into paragraphs, and paragraphs into export formats.
// Everything here is pure: data in, strings out.

import type { Chapter, Paragraph, Snippet, Transcript } from './types';
import { fmtTime, wordCount } from './format';
import { watchUrl } from './links';

const SOUND_TAG = /\[(?:music|applause|laughter|laughs|cheering|inaudible|silence|__|sound|noise)[^\]]*\]|♪+/gi;

export function cleanText(text: string, hideTags: boolean) {
  text = text.replace(/\s+/g, ' ').trim();
  if (hideTags) text = text.replace(SOUND_TAG, '').replace(/\s+/g, ' ').trim();
  return text;
}

/**
 * Group caption fragments into readable paragraphs.
 * A new paragraph starts at a speaker change (">>" or "- "), a pause over 2.5s, a chapter
 * boundary, or once a paragraph runs long (90+ words at a sentence end, or 170 regardless).
 * Each paragraph that opens a chapter carries that chapter on `chapter`.
 */
export function buildParagraphs(snippets: Snippet[], { hideTags = true, chapters = [] as Chapter[] } = {}): Paragraph[] {
  const paras: Paragraph[] = [];
  let cur: Paragraph | null = null, prevEnd = 0, ci = 0, pendingChapter: Chapter | null = null;

  for (const sn of snippets) {
    // Claim every chapter that starts at or before this snippet (half-second tolerance).
    while (ci < chapters.length && chapters[ci].start <= sn.start + 0.5) pendingChapter = chapters[ci++];

    let text = cleanText(sn.text, hideTags);
    if (!text) { prevEnd = sn.start + sn.duration; continue; }

    const speakerChange = /^(>>|-\s)/.test(text);
    text = text.replace(/^>>\s*/, '');

    let breakHere = !cur || speakerChange || !!pendingChapter || sn.start - prevEnd > 2.5;
    if (!breakHere && cur) {
      const words = wordCount(cur.text);
      const endsSentence = /[.!?]["')\]]?$/.test(cur.text);
      breakHere = (words > 90 && endsSentence) || words > 170;
    }

    if (breakHere || !cur) {
      if (cur) paras.push(cur);
      cur = { start: sn.start, text, chapter: pendingChapter };
      pendingChapter = null;
    } else {
      cur.text += ' ' + text;
    }
    prevEnd = sn.start + sn.duration;
  }
  if (cur) paras.push(cur);

  return paras.map(p => {
    const t = p.text.replace(/\s+([,.!?;:])/g, '$1').trim();
    return { ...p, text: t.charAt(0).toUpperCase() + t.slice(1) };
  });
}

/* ---------- Formats ---------- */

export type ExportContext = { data: Transcript; paras: Paragraph[]; chapters?: Chapter[]; ts: boolean; hideTags: boolean };

const titleOf = (data: Transcript) => data.title || 'YouTube video';

export function languageLine(data: Transcript) {
  if (data.translation) return `${data.translation.name} (translated from ${data.language})`;
  return `${data.language}${data.isGenerated ? ', auto-generated' : ''}`;
}

export function plainText({ data, paras, ts }: ExportContext) {
  const head = [titleOf(data), data.author && `Channel: ${data.author}`, watchUrl(data.videoId)].filter(Boolean).join('\n');
  const body = paras.map(p => {
    const line = (ts ? `[${fmtTime(p.start)}] ` : '') + p.text;
    return p.chapter ? `## ${p.chapter.title}\n\n${line}` : line;
  }).join('\n\n');
  return `${head}\n\n${body}\n`;
}

export function markdown({ data, paras, ts }: ExportContext) {
  const url = watchUrl(data.videoId);
  const head = `# ${titleOf(data)}\n\n` + (data.author ? `**Channel:** ${data.author}  \n` : '') + `**Link:** ${url}\n`;
  const body = paras.map(p => {
    const line = (ts ? `**[${fmtTime(p.start)}](${watchUrl(data.videoId, p.start)})** ` : '') + p.text;
    return p.chapter ? `## ${p.chapter.title}\n\n${line}` : line;
  }).join('\n\n');
  return `${head}\n${body}\n`;
}

function cues({ data, hideTags }: ExportContext) {
  return data.snippets
    .map(sn => ({ start: sn.start, end: sn.start + sn.duration, text: cleanText(sn.text, hideTags) }))
    .filter(c => c.text);
}

function clock(sec: number, sep: string) {
  const ms = Math.round(sec * 1000), p = (n: number, w = 2) => String(n).padStart(w, '0');
  return `${p(Math.floor(ms / 3600000))}:${p(Math.floor((ms % 3600000) / 60000))}:${p(Math.floor((ms % 60000) / 1000))}${sep}${p(ms % 1000, 3)}`;
}

export function srt(ctx: ExportContext) {
  return cues(ctx).map((c, i) => `${i + 1}\n${clock(c.start, ',')} --> ${clock(c.end, ',')}\n${c.text}\n`).join('\n');
}

export function vtt(ctx: ExportContext) {
  return 'WEBVTT\n\n' + cues(ctx).map(c => `${clock(c.start, '.')} --> ${clock(c.end, '.')}\n${c.text}\n`).join('\n');
}

export function jsonRecord(ctx: ExportContext) {
  const { data, paras, chapters = [] } = ctx;
  return {
    videoId: data.videoId,
    url: watchUrl(data.videoId),
    title: data.title,
    channel: data.author,
    language: data.language,
    languageCode: data.languageCode,
    autoGenerated: data.isGenerated,
    translation: data.translation,
    chapters,
    paragraphs: paras.map(p => ({ start: p.start, text: p.text, ...(p.chapter && { chapter: p.chapter.title }) })),
    snippets: cues(ctx),
  };
}

export const toJSON = (ctx: ExportContext) => JSON.stringify(jsonRecord(ctx), null, 2) + '\n';

export function csv(ctx: ExportContext) {
  const q = (s: string) => `"${s.replace(/"/g, '""')}"`;
  const rows = cues(ctx).map(c => [c.start.toFixed(2), c.end.toFixed(2), fmtTime(c.start), q(c.text)].join(','));
  return ['start_seconds,end_seconds,timestamp,text', ...rows].join('\r\n') + '\r\n';
}

export const FORMATS = {
  txt:  { fn: plainText, ext: 'txt',  type: 'text/plain' },
  md:   { fn: markdown,  ext: 'md',   type: 'text/markdown' },
  srt:  { fn: srt,       ext: 'srt',  type: 'application/x-subrip' },
  vtt:  { fn: vtt,       ext: 'vtt',  type: 'text/vtt' },
  json: { fn: toJSON,    ext: 'json', type: 'application/json' },
  csv:  { fn: csv,       ext: 'csv',  type: 'text/csv' },
} as const;
export type Format = keyof typeof FORMATS;

/* ---------- Prompts for "Copy for summary" ---------- */

export function summaryPrompt(hasChapters: boolean) {
  return 'Summarize this YouTube video transcript. Give a short overview, then the key points as bullets'
    + (hasChapters ? ', following the chapter headings' : '')
    + ', then any actionable takeaways.\n\n---\n\n';
}

export function bulkPrompt(n: number) {
  return `Summarize each of these ${n} YouTube video transcripts. For each one, give a short overview and the key points as bullets. `
    + 'Then finish with the themes that run across them and any actionable takeaways.\n\n---\n\n';
}
